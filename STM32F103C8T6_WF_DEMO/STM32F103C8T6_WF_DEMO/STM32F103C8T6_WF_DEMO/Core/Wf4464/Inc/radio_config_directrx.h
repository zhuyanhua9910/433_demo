  #define RF_DIRECTRX_FREQ_BYTES  0x38, 0x0E, 0xD9, 0x16
#else
  /* 433.000 MHz: INTE=0x38, FRAC=0x0DDDDD -> (56 + 908765/2^19) x 30MHz/4 */
  #define RF_DIRECTRX_FREQ_BYTES  0x38, 0x0D, 0xDD, 0xDD
#endif

/* FREQ_CONTROL_INTE, FREQ_CONTROL_FRAC_2, FREQ_CONTROL_FRAC_1, FREQ_CONTROL_FRAC_0, FREQ_CONTROL_CHANNEL_STEP_SIZE_1, FREQ_CONTROL_CHANNEL_STEP_SIZE_0, FREQ_CONTROL_W_SIZE, FREQ_CONTROL_VCOCNT_RX_ADJ */
